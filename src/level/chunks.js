// Hand-authored level chunks as ASCII maps, stitched together by
// generator.js. Each row is 18 characters: the inner shaft between the two
// unbreakable border columns. Top row = how you come in, bottom row = how
// you leave. The generator carves a sideways tunnel between one chunk's exit
// and the next chunk's entry, so chunks don't need to line up.
//
//   .  empty                 #  dirt (Drill / Wall Burrow only)
//   S  soft dirt (dig down or tunnel sideways through it)
//   R  rock (unbreakable)    =  ledge (one-way; jump up through, dig down)
//   ~  fragile ledge (breaks: Parachute Snap, rocks; diggable)
//   ^  spikes (solid; hurts when you land on top)
//   P  pad (bounces you up)
//   K  loose rocks: a rockfall that drops when you pass underneath
//   o  thorn ball            O  thorn that patrols its row
//   v  down-ring (diving through = speed burst)
//   c  carrot slot           ?  thorn slot (filled by difficulty)
//   !  spikes by chance, else dirt      %  fragile by chance, else ledge
//
// Keep passages at least 2 tiles wide and 2 tall (the rabbit is 22x26 and a
// tile is 18). Chunks are mirrored at random, so author one side.
//   diff   tier (0-3), unlocks with depth (config.difficulty.tierDepths)
//   weight optional pick weight (default 1)

